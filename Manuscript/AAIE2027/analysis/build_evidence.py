"""Regenerate aggregate evidence and LaTeX numbers from unchanged CSV exports.

Run from the repository root:
    python3 Manuscript/AAIE2027/analysis/build_evidence.py
Requires Python 3 and Node.js; no application or database is started.
"""
import hashlib
import json
from pathlib import Path
import subprocess
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
result = subprocess.run([sys.executable, str(HERE / 'audit_csv.py')], cwd=ROOT,
                        capture_output=True, text=True, check=True)
report = json.loads(result.stdout)
coverage = report['response_coverage']
inventory = report['inventory']
expected_snapshot = {
    'responses': 'fb4bf972780e96dcf4f6be74d83333603c035656016b4272b1b28ea42aa9b9c7',
    'content_items': 'c56af9da4536024403c85ac7e3d8907bb21ae463270a30b408a81d6be45eb311',
    'knowledge_components': 'b90be9a767dd23ffc751301f69678d843e41b6cbd71af2a96a07e1fb9a6b550b',
}
for name, digest in expected_snapshot.items():
    if inventory[name]['sha256'] != digest:
        raise SystemExit('Different CSV snapshot detected. Reaudit and review all manuscript results before regenerating evidence.')
if report['source_fingerprints']['client/src/components/student/QuizView.js'] != '4305b1a73e81e55b06aa69f9b4c3a223f49b833d2ad0fda806983a6451bfe428':
    raise SystemExit('Client validator source changed. Review diagnostic comparability before regenerating evidence.')
count = inventory['responses']['rows']
labels = coverage['correct_stored']
assert sum(labels.values()) == count
checks = report['answer_diagnostics_not_relabeling']['current_client_validator_counts']
assert sum(checks.values()) == count
for entry in inventory.values():
    assert hashlib.sha256((ROOT / entry['path']).read_bytes()).hexdigest() == entry['sha256']

values = {
    'ResponseCount': f'{count:,}',
    'StudentIDCount': coverage['student_ids_not_verified_people'],
    'CatalogItemCount': inventory['content_items']['rows'],
    'CatalogKCCount': inventory['knowledge_components']['rows'],
    'ObservedItemCount': coverage['observed_item_ids'],
    'ObservedKCCount': coverage['observed_kc_ids'],
    'TrueCount': f"{labels.get('true', 0):,}",
    'BlankCount': labels.get('NULL', 0),
    'BlankPercent': f"{100 * labels.get('NULL', 0) / count:.2f}",
    'SequenceCount': coverage['student_kc_sequences'],
    'EightSequenceCount': coverage['student_kc_length_frequencies'].get('8', 0),
    'RepeatCount': coverage['repeat_student_item_records'],
    'PracticeCount': report['interaction_data']['practice_flag_values'].get('True', 0),
    'SequentialCount': f"{report['interaction_data']['quiz_mode_values'].get('sequential', 0):,}",
    'AttemptRecordedCount': f"{report['interaction_data']['attempt_values'].get('1', 0):,}",
    'HintOneCount': report['interaction_data']['hint_request_values'].get('1', 0),
    'DayWindowRows': f"{sum(coverage['records_by_day_UTC'][date]['rows'] for date in ['2025-07-02', '2025-07-03', '2025-07-04']):,}",
    'TimerIncreaseCount': f"{report['time_diagnostics']['successive_stored_times'].get('increase', 0):,}",
    'TimerDecreaseCount': report['time_diagnostics']['successive_stored_times'].get('decrease', 0),
    'DescriptiveSessionCount': report['time_diagnostics']['sessions_using_descriptive_30_minute_gap_only'],
}
(HERE / 'audit_results.json').write_text(json.dumps(report, indent=2, sort_keys=True) + '\n')
tex = '% Generated by analysis/build_evidence.py; do not edit measured values manually.\n'
tex += ''.join('\\newcommand{\\' + name + '}{' + str(value) + '}\n' for name, value in values.items())
(HERE.parent / 'evidence_numbers.tex').write_text(tex)
print('Generated aggregate audit_results.json and evidence_numbers.tex; raw CSV hashes verified unchanged.')
